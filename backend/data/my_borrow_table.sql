-- 1. สร้างตารางเก็บข้อมูลผู้ใช้ (Profiles)
CREATE TABLE profiles (
    id TEXT PRIMARY KEY,
    name TEXT NOT NULL,
    email TEXT NOT NULL,
    avatar_url TEXT
);


CREATE TABLE borrow_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id TEXT REFERENCES profiles(id), -- คอลัมน์นี้สำคัญมาก! ใช้ผูกว่าใครยืม
    name TEXT NOT NULL,
    category TEXT,
